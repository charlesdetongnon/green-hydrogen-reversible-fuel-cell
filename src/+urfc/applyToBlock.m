function applyToBlock(block, par)
%APPLYTOBLOCK Write a cell parameter structure to a URFC Simscape block.
%   urfc.applyToBlock(BLOCK, PAR) sets the parameters of the
%   greenH2.ReversibleFuelCell block BLOCK from the structure PAR (see
%   urfc.defaultParameters), including the physical units. This keeps the
%   Simscape component and urfc.cellModel on the same parameter set.

arguments
    block (1,1) string
    par (1,1) struct
end

num = @(x) num2str(x, 17);
set_param(block, ...
    'N_cell', num(par.nCell), ...
    'A_cell', num(par.aCell), 'A_cell_unit', 'cm^2', ...
    't_mem', num(par.tMem), 't_mem_unit', 'cm', ...
    'lambda_EC', num(par.lambdaEC), 'lambda_FC', num(par.lambdaFC), ...
    'R_contact', num(par.rContact), 'R_contact_unit', 'Ohm*cm^2', ...
    'j0_EC', num(par.j0EC), 'j0_EC_unit', 'A/cm^2', ...
    'alpha_EC', num(par.alphaEC), ...
    'j0_FC', num(par.j0FC), 'j0_FC_unit', 'A/cm^2', ...
    'alpha_FC', num(par.alphaFC), 'gamma_O2', num(par.gammaO2), ...
    'E_a', num(par.Ea), 'E_a_unit', 'J/mol', ...
    'T_ref', num(par.Tref), 'T_ref_unit', 'K', ...
    'jL_EC', num(par.jLEC), 'jL_EC_unit', 'A/cm^2', ...
    'jL_FC', num(par.jLFC), 'jL_FC_unit', 'A/cm^2', ...
    'psi_H2', num(par.psiH2), 'psi_H2_unit', 'mol/(cm*s*bar)');
end
